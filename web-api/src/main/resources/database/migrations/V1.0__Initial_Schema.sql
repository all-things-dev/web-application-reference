-- Extensions

-- users

DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users
(
	id                 BIGINT    NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

	uid                UUID      NOT NULL UNIQUE DEFAULT UUIDV7(),

	first_name         TEXT      NOT NULL,
	last_name          TEXT      NOT NULL,

	is_active          BOOLEAN   NOT NULL        DEFAULT TRUE,

	created_by         BIGINT    NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
	updated_by         BIGINT    NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
	deleted_by         BIGINT    NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,

	creation_timestamp TIMESTAMP NOT NULL        DEFAULT CLOCK_TIMESTAMP(),
	update_timestamp   TIMESTAMP NOT NULL        DEFAULT CLOCK_TIMESTAMP(),
	deletion_timestamp TIMESTAMP NULL,

	version            INTEGER   NOT NULL        DEFAULT 0
);

-- audit_actions

DROP TABLE IF EXISTS audit_actions CASCADE;

CREATE TABLE audit_actions
(
	id                 SMALLINT  NOT NULL PRIMARY KEY,

	name               TEXT      NOT NULL,

	creation_timestamp TIMESTAMP NOT NULL DEFAULT CLOCK_TIMESTAMP()
);

INSERT INTO audit_actions (id, name) VALUES (1, 'CREATE'), (2, 'UPDATE'), (3, 'DELETE');

-- audit_logs

DROP TABLE IF EXISTS audit_logs CASCADE;

CREATE TABLE audit_logs
(
	id                 BIGINT    NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

	table_name         TEXT      NOT NULL,
	action_id          SMALLINT  NOT NULL REFERENCES audit_actions (id) ON UPDATE CASCADE ON DELETE RESTRICT,

	changes            JSONB     NOT NULL DEFAULT '{}',

	created_by         BIGINT    NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,

	creation_timestamp TIMESTAMP NOT NULL DEFAULT CLOCK_TIMESTAMP()
);